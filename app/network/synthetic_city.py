def _ceil_to(value: float, decimals: int) -> float:
    factor = 10**decimals
    return math.ceil(value * factor) / factor


def _km_to_latlon(x_km: float, y_km: float) -> tuple[float, float]:
    lat = SYNTHETIC_ANCHOR_LAT + y_km / KM_PER_DEGREE_LAT
    lon = SYNTHETIC_ANCHOR_LON + x_km / (KM_PER_DEGREE_LAT * math.cos(math.radians(SYNTHETIC_ANCHOR_LAT)))
    return round(lat, 6), round(lon, 6)


def generate_synthetic_city_dict(seed: int = DEFAULT_SEED) -> dict[str, Any]:
    """Return a complete scenario dict for the synthetic city."""
    if isinstance(seed, bool) or not isinstance(seed, int):
        raise TypeError("seed must be an int")
    rng = random.Random(seed)

    nodes: list[dict[str, Any]] = []
    coords: dict[str, tuple[float, float]] = {}
    for node_id, name, node_type, x_km, y_km in NODE_LAYOUT:
        jx = rng.uniform(-COORDINATE_JITTER_KM, COORDINATE_JITTER_KM)
        jy = rng.uniform(-COORDINATE_JITTER_KM, COORDINATE_JITTER_KM)
        lat, lon = _km_to_latlon(x_km + jx, y_km + jy)
        coords[node_id] = (lat, lon)
        nodes.append({"node_id": node_id, "name": name, "latitude": lat,
                      "longitude": lon, "node_type": node_type})

    low_u, high_u = BASELINE_UTILIZATION_RANGE
    edges: list[dict[str, Any]] = []
    for a, b, road_type in ROAD_LINKS:
        profile = ROAD_TYPE_PROFILES[road_type]
        straight = haversine_km(*coords[a], *coords[b])
        detour = rng.uniform(profile.detour_factor_min, profile.detour_factor_max)
        distance = _ceil_to(straight * detour, 3)
        base_time = _ceil_to(distance / profile.nominal_speed_kmh * 60.0, 2)
        for src, dst in ((a, b), (b, a)):
            count = int(profile.default_capacity_vph * rng.uniform(low_u, high_u))
            edges.append({
                "edge_id": f"E{len(edges) + 1:03d}",
                "source": src,
                "destination": dst,
                "distance_km": distance,
                "base_travel_time_min": base_time,
                "capacity_vehicles_per_hour": profile.default_capacity_vph,
                "current_vehicle_count": count,
                "road_type": road_type,
            })

    return {
        "schema_version": SCENARIO_SCHEMA_VERSION,
        "scenario_id": "baseline",
        "description": "Milestone 1 baseline: 22-node synthetic city with an east-west trunk "
                       "corridor, arterial alternatives and local streets.",
        "data_provenance": PROVENANCE,
        "seed": seed,
        "assumptions": {
            "units": {"distance": "km", "time": "minutes", "capacity": "vehicles per hour"},
            "network_max_speed_kmh": NETWORK_MAX_SPEED_KMH,
            "congestion_model": {
                "formula": "u = count/capacity; if u<=1: m = 1 + alpha*u^beta; "
                           "else: m = 1 + alpha + overload_slope*(u-1); time = base_time*m",
                "parameters": DEFAULT_CONGESTION.to_dict(),
                "note": "alpha/beta are classic BPR values; overload_slope is a project assumption.",
            },
            "road_type_profiles": {k: v.to_dict() for k, v in ROAD_TYPE_PROFILES.items()},
            "baseline_utilization_range": list(BASELINE_UTILIZATION_RANGE),
            "coordinate_jitter_km": COORDINATE_JITTER_KM,
            "coordinate_anchor": {"latitude": SYNTHETIC_ANCHOR_LAT, "longitude": SYNTHETIC_ANCHOR_LON,
                                  "note": "Arbitrary anchor; not a real city."},
            "a_star_heuristic": "straight-line km / network_max_speed_kmh * 60 * 0.999 (admissible)",
        },
        "simulation": {"start_time_min": 0.0},
        "nodes": nodes,
        "edges": edges,
    }


def build_synthetic_city(seed: int = DEFAULT_SEED) -> LoadedScenario:
    return scenario_from_dict(generate_synthetic_city_dict(seed))
