"""Deterministic SYNTHETIC city generator.

*** ALL DATA HERE IS SYNTHETIC. It does not describe any real city. ***

Method
------
1. A hand-authored layout places 22 named nodes on a local km grid
   (x = east, y = north) around an arbitrary anchor coordinate.
2. A seeded ``random.Random(seed)`` adds small coordinate jitter.
3. 28 hand-authored road links become 56 directed edges (both directions).
   Road distance = straight-line distance x seeded detour factor (per road type),
   rounded UP; base time = distance / nominal road-type speed, rounded UP.
   Rounding up guarantees the geometry rules that keep A* admissible.
4. Each directed edge gets a seeded baseline vehicle count.

The only randomness comes from the local RNG, consumed in a fixed order, so the
same seed always yields byte-identical output.
"""

